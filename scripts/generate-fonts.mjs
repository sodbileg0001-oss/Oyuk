import { readFile, writeFile } from 'node:fs/promises'

// Preserve Fontsource's unicode ranges: separate subset imports without ranges can override each other.
const families = { 'noto-serif': ['400', '400-italic', '500'], 'noto-sans': ['400', '500', '600'] }
let css = '/* Self-hosted Latin + Cyrillic + extended Cyrillic, including Ү ү Ө ө. Generated by scripts/generate-fonts.mjs. */\n'
for (const [family, weights] of Object.entries(families)) {
  for (const weight of weights) {
    const source = await readFile(`node_modules/@fontsource/${family}/${weight}.css`, 'utf8')
    const blocks = source.match(/\/\*[^*]+\*\/\s*@font-face\s*\{[^}]+\}/g) ?? []
    for (const block of blocks) {
      if (!new RegExp(`${family}-(latin|cyrillic|cyrillic-ext)-\\d`).test(block.split('\n')[0])) continue
      css += block.replace(/url\(\.\/files\//g, `url(@fontsource/${family}/files/`).replace(/, url\([^)]*\.woff\) format\('woff'\)/g, '') + '\n\n'
    }
  }
}
await writeFile('src/styles/fonts.css', css)
console.log('Prepared Noto fonts with explicit Cyrillic and extended-Cyrillic ranges.')
